//! Binary G-code: the container the writer emits and the reader takes back.

use hfw_config::PrinterConfig;
use hfw_gcode::bgcode::{self, BgcodeError, BlockType};
use hfw_gcode::thumb::{Format, Image};
use hfw_gcode::{Gcode, GcodeStats};

fn config() -> PrinterConfig {
    PrinterConfig::parse(
        "printer_model = Voron 2.4\nprinter_variant = 0.4\nnozzle_diameter = 0.4\n",
    )
    .expect("the profile parses")
}

fn gcode(text: &str, thumbnails: Vec<Image>) -> Gcode {
    Gcode {
        text: text.to_owned(),
        stats: GcodeStats {
            layers: 2,
            volume_mm3: 12.5,
            filament_mm: 5.25,
            filament_g: 0.04,
            est_seconds: 42.0,
            ..GcodeStats::default()
        },
        thumbnails,
    }
}

const TEXT: &str =
    "; generated by HFW\nG28 ; home\nG1 X10.000 Y10.000 E1.000\nG1 X20.000 Y10.000 E2.000\n";

fn png_bytes() -> Vec<u8> {
    let mut bytes = vec![0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A];
    bytes.extend_from_slice(b"synthetic payload");
    bytes
}

/// A container built by hand, so a test can write a block the encoder never
/// writes: one that claims a compression, or an encoding.
fn container(checksum: u16, blocks: &[(u16, u16, [u8; 2], Vec<u8>)]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(&bgcode::MAGIC);
    out.extend_from_slice(&bgcode::VERSION.to_le_bytes());
    out.extend_from_slice(&checksum.to_le_bytes());
    for (kind, compression, parameters, data) in blocks {
        out.extend_from_slice(&kind.to_le_bytes());
        out.extend_from_slice(&compression.to_le_bytes());
        out.extend_from_slice(&(data.len() as u32).to_le_bytes());
        out.extend_from_slice(parameters);
        out.extend_from_slice(data);
        if checksum != 0 {
            out.extend_from_slice(&0u32.to_le_bytes());
        }
    }
    out
}

fn find(bytes: &[u8], needle: &[u8]) -> usize {
    bytes
        .windows(needle.len())
        .position(|window| window == needle)
        .unwrap_or_else(|| panic!("the encoded file does not hold {needle:?}"))
}

#[test]
fn an_encoded_file_decodes_to_the_text_it_was_written_from() {
    let file = bgcode::encode(&gcode(TEXT, Vec::new()), &config());
    assert_eq!(&file[..4], b"GCDE");
    assert_eq!(u32::from_le_bytes([file[4], file[5], file[6], file[7]]), 1);
    assert_eq!(
        u16::from_le_bytes([file[8], file[9]]),
        1,
        "CRC32 by default"
    );

    let decoded = bgcode::decode(&file).expect("the file decodes");
    assert_eq!(decoded.text, TEXT);
    assert_eq!(decoded.blocks, 5, "file, printer, print, slicer and gcode");
    assert_eq!(decoded.thumbnails.len(), 0);
    let model = decoded
        .printer
        .iter()
        .find(|(key, _)| key == "printer_model")
        .map(|(_, value)| value.as_str());
    assert_eq!(model, Some("Voron 2.4"));
}

#[test]
fn a_thumbnail_lands_in_its_own_block_with_the_bytes_it_was_given() {
    let image = Image {
        width: 64,
        height: 48,
        format: Format::Png,
        bytes: png_bytes(),
    };
    let file = bgcode::encode(&gcode(TEXT, vec![image.clone()]), &config());
    let decoded = bgcode::decode(&file).expect("the file decodes");
    assert_eq!(decoded.blocks, 6, "one thumbnail block was added");
    assert_eq!(decoded.thumbnails.len(), 1);
    assert_eq!(decoded.thumbnails[0], image);
    assert_eq!(decoded.text, TEXT, "the text does not carry the image");
}

#[test]
fn a_flipped_byte_fails_the_checksum() {
    let file = bgcode::encode(&gcode(TEXT, Vec::new()), &config());
    let at = find(&file, b"G1 X20.000");
    let mut damaged = file.clone();
    damaged[at] ^= 0x01;
    match bgcode::decode(&damaged) {
        Err(BgcodeError::BadChecksum {
            block,
            recorded,
            computed,
        }) => {
            assert_eq!(block, BlockType::Gcode.code());
            assert_ne!(recorded, computed);
        }
        other => panic!("a damaged block decoded as {other:?}"),
    }
}

#[test]
fn a_truncated_file_is_refused() {
    let file = bgcode::encode(&gcode(TEXT, Vec::new()), &config());
    assert_eq!(
        bgcode::decode(&file[..file.len() - 2]),
        Err(BgcodeError::Truncated {
            what: "a block's checksum"
        })
    );
    assert_eq!(
        bgcode::decode(&file[..6]),
        Err(BgcodeError::Truncated {
            what: "the file header"
        })
    );
}

#[test]
fn a_file_that_is_not_bgcode_is_refused() {
    assert_eq!(
        bgcode::decode(b"GCODE, roughly, but not the container"),
        Err(BgcodeError::NotBgcode)
    );
    let mut wrong_version = bgcode::encode(&gcode(TEXT, Vec::new()), &config());
    wrong_version[4] = 2;
    assert_eq!(
        bgcode::decode(&wrong_version),
        Err(BgcodeError::UnsupportedVersion(2))
    );
}

#[test]
fn a_compressed_block_is_refused_by_name() {
    let file = container(0, &[(1, 1, [0, 0], b"xxxx".to_vec())]);
    assert_eq!(
        bgcode::decode(&file),
        Err(BgcodeError::Compressed {
            block: 1,
            algorithm: 1
        })
    );
}

#[test]
fn an_encoded_gcode_block_is_refused_by_name() {
    let file = container(0, &[(1, 0, [2, 0], b"G28\n".to_vec())]);
    assert_eq!(
        bgcode::decode(&file),
        Err(BgcodeError::Encoded {
            block: 1,
            algorithm: 2
        })
    );
}

#[test]
fn an_undefined_block_type_is_refused() {
    let file = container(0, &[(9, 0, [0, 0], Vec::new())]);
    assert_eq!(bgcode::decode(&file), Err(BgcodeError::UnknownBlock(9)));
}
