#!/usr/bin/env python3
"""Generates `crates/config/src/alias_table.rs` from the ledger's rename table.

One mapping, one source. `tools/gen-settings-ledger.py` records which engine
setting each of this crate's own keys corresponds to; this script turns exactly
those entries into a lookup the native parser uses, so a profile written with
engine names loads with validation instead of dying on `unknown setting`.

Only entries the ledger records as `applied` are aliased: a `partial` mapping
means the two settings do not mean the same thing, and silently accepting one
for the other is how a profile ends up slicing with a value nobody chose.

    tools/gen-alias-table.py            rewrite the table
    tools/gen-alias-table.py --check    fail if the committed table is stale
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PARSE = ROOT / "crates/config/src/parse.rs"
RENAMES = ROOT / "crates/config/src/dialect_table.rs"
LEDGER_TOOL = ROOT / "tools/gen-settings-ledger.py"
TARGET = ROOT / "crates/config/src/alias_table.rs"

HEADER = '''//! Generated by `tools/gen-alias-table.py` — do not edit by hand.
//!
//! Engine setting name to this crate's key, for every mapping the settings
//! ledger records as applied. `PrinterConfig::assign` consults this table
//! before its own arms, so a profile written in the engine's dialect loads
//! with the same validation as a native one.

/// This crate's key for an engine setting name, when the two mean the same
/// thing.
pub fn native_for(name: &str) -> Option<&'static str> {
    match name {
'''''

FOOTER = '''    _ => None,
    }
}
'''


def native_keys() -> set[str]:
    text = PARSE.read_text(encoding="utf-8")
    return set(re.findall(r'^            "([a-z0-9_]+)" =>', text, re.M))


def orca_renames() -> dict[str, str]:
    """Orca spelling to engine spelling, from the generated rename table."""
    if not RENAMES.exists():
        return {}
    text = RENAMES.read_text(encoding="utf-8")
    start = text.find("pub const RENAMES")
    if start < 0:
        return {}
    end = text.find("];", start)
    if end < 0:
        return {}
    return dict(
        re.findall(
            r'\(\s*"([a-z0-9_]+)",\s*"([a-z0-9_]+)",?\s*\)', text[start:end]
        )
    )


def ledger_aliases() -> dict[str, str]:
    spec = importlib.util.spec_from_file_location("ledger", LEDGER_TOOL)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {LEDGER_TOOL}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    native = native_keys()
    aliases: dict[str, str] = {}
    for engine, (key, status, _note) in module.HFW_SYNONYMS.items():
        if status != "applied" or key not in native or engine == key:
            continue
        if not re.fullmatch(r"[a-z0-9_]+", engine):
            continue
        aliases[engine] = key
    for key, (engine, status, _note) in module.HFW_ALIAS.items():
        if engine is None or status != "applied":
            continue
        if engine == key:
            continue
        if key not in native:
            continue
        if not re.fullmatch(r"[a-z0-9_]+", engine):
            continue
        aliases[engine] = key
    # OrcaSlicer renamed many of the engine's own settings (`wall_loops` for
    # `perimeters`). Those names reach the engine through the rename table, so
    # they reach this crate the same way rather than being a second dialect.
    for orca_name, engine in orca_renames().items():
        key = aliases.get(engine)
        if key is None and engine in native:
            key = engine
        if key is None or orca_name == key:
            continue
        aliases.setdefault(orca_name, key)
    return aliases


def render(aliases: dict[str, str]) -> str:
    lines = [HEADER]
    for engine, native in sorted(aliases.items()):
        lines.append(f'        "{engine}" => Some("{native}"),\n')
    lines.append(FOOTER)
    return "".join(lines)


def rustfmt_text(text: str) -> str:
    """Formats generated Rust the way `cargo fmt` will, so the tree stays clean."""
    try:
        result = subprocess.run(
            ["rustfmt", "--edition", "2021", "--emit", "stdout"],
            input=text,
            capture_output=True,
            text=True,
            timeout=60,
        )
    except (OSError, subprocess.SubprocessError):
        return text
    if result.returncode != 0 or not result.stdout.strip():
        return text
    return result.stdout


def main() -> int:
    aliases = ledger_aliases()
    if len(aliases) < 20:
        print(f"only {len(aliases)} aliases found: the ledger table moved?", file=sys.stderr)
        return 1
    text = rustfmt_text(render(aliases))
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(
                f"{TARGET.relative_to(ROOT)} is stale; run tools/gen-alias-table.py",
                file=sys.stderr,
            )
            return 1
        print(f"alias table: {len(aliases)} aliases, up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(aliases)} aliases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
